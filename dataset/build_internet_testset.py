#!/usr/bin/env python3
"""
TruthLens — Internet Test Set Builder
======================================
Downloads real photographs and AI-generated images from Wikimedia Commons into
``datasets/evaluation/internet/``, to test the detector on images that came from the open
internet rather than from any dataset it was trained on.

Why a separate harness and not just a test split
-------------------------------------------------
``datasets/prepared/modern_v2/test`` is a held-out split of the *same* uploads as the
training half. Sharing a source means sharing its quirks — one uploader's export
settings, one scraper's re-encoding, one week of one platform's traffic. A model
can ride those and still fail on an arbitrary image, which is the failure being
chased here. Commons is independent of every source in the collector, so a score
here is a fairer estimate of what a user actually sees.

Three properties of this set, and what each costs
-------------------------------------------------
1. **Every image arrives as a 1280px JPEG from Wikimedia's thumbnailer.**
   Not a choice — ``upload.wikimedia.org`` answers bulk requests for originals
   with HTTP 429 and points at the thumbnail sizes instead. It turns out to be
   the more useful test anyway: both classes pass through the identical encoder
   at the identical size, so container format, file size and resolution carry
   *zero* class information. The format shortcut cannot be exploited here even
   in principle. The cost is that a fingerprint only visible in pristine bytes
   would be invisible — but such a fingerprint is useless in production too,
   since almost every image reaching the app has been through some platform's
   encoder.

2. **Subjects are matched across classes.** The AI categories on Commons skew to
   people, landscapes and food, so the real categories were chosen to cover the
   same three. Left unmatched — AI portraits against real landscapes — a model
   could score well by recognising subject matter and never look at texture.

3. **The AI label is trustworthy; "is a photograph" is not.** Commons requires
   uploaders to declare AI generation, so ``fake`` is reliable. But those
   categories are not curated for photorealism: they also hold logos, diagrams
   and cartoons. ``--min-pixels`` removes icons, and every title is recorded in
   the manifest so non-photographic entries can be identified. Read per-image
   results, not only the mean.

Nothing here is training data. Commons content is CC/public-domain and fine to
redistribute, but this set exists to be *scored against*; folding it into
training would destroy the one independent measurement available.

Usage
-----
    python dataset/build_internet_testset.py --per-class 120
    python dataset/build_internet_testset.py --report
"""

from __future__ import annotations

import argparse
import collections
import hashlib
import json
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Dict, Iterator, List, Optional, Tuple

ROOT_DIR = Path(__file__).resolve().parent.parent
DATASETS_DIR = ROOT_DIR / "datasets"
OUTPUT_DIR = DATASETS_DIR / "evaluation" / "internet"
MANIFEST_PATH = OUTPUT_DIR / "manifest.jsonl"

API = "https://commons.wikimedia.org/w/api.php"
# Wikimedia's UA policy wants a descriptive agent identifying the tool.
UA = "TruthLens-research/1.0 (AI-image-detection evaluation; non-commercial)"

# Width requested from the thumbnailer. 1280 is a standard cached size, so it is
# served from CDN rather than rendered per request.
THUMB_WIDTH = 1280

MIN_INTERVAL = 2.0      # seconds between requests — see the throttling note below

# Wikimedia serves originals from ``upload.wikimedia.org`` under a strict bulk
# policy and answers sustained automated traffic with HTTP 429. The throttle is
# per-IP and persists for a while after it trips, so a fast first attempt makes
# the *next* attempt fail too. One request every two seconds, single-threaded,
# stays under it; 280 images then takes about ten minutes, which is the right
# trade for a set that only has to be built once. ``--interval`` overrides it.
#
# ``MAX_CONSECUTIVE_429`` exists so a tripped throttle fails loudly instead of
# grinding through the whole category list and leaving a four-image test set that
# looks like a finished one.
MAX_CONSECUTIVE_429 = 12


class Throttled(RuntimeError):
    """Raised when Wikimedia has rate-limited this IP and backing off is futile."""

# Commons categories per class, tagged for the manifest. Several per class so no
# single uploader or subject defines a class; subjects deliberately overlap
# between real and fake (people / landscape / food / flora).
CATEGORIES: Dict[str, List[Tuple[str, str]]] = {
    "fake": [
        ("Images generated by DALL-E",       "ai-dalle"),
        ("Images generated by ChatGPT",      "ai-chatgpt"),
        ("Images generated by Midjourney",   "ai-midjourney"),
        ("AI-generated landscapes",          "ai-landscape"),
        ("AI-generated portraits",           "ai-portrait"),
        ("Images generated by Grok",         "ai-grok"),
        ("Images generated by Imagen",       "ai-imagen"),
    ],
    "real": [
        ("Quality images of people",         "photo-people"),
        ("Featured pictures of landscapes",  "photo-landscape"),
        ("Quality images of food",           "photo-food"),
        ("Quality images of flowers",        "photo-flowers"),
        ("Featured pictures of people",      "photo-people-fp"),
        ("Quality images of architecture",   "photo-architecture"),
        ("Quality images of birds",          "photo-birds"),
    ],
}

IMAGE_EXT = (".jpg", ".jpeg", ".png", ".webp")

_last_request = [0.0]
_consecutive_429 = [0]


def _throttle() -> None:
    """Keep at least MIN_INTERVAL between outbound requests."""
    wait = MIN_INTERVAL - (time.monotonic() - _last_request[0])
    if wait > 0:
        time.sleep(wait)
    _last_request[0] = time.monotonic()


def _fetch(url: str, retries: int = 3, timeout: int = 60) -> Optional[bytes]:
    """GET with throttling and 429-aware backoff. ``None`` on give-up.

    Raises ``Throttled`` once 429s stop being incidental, so the caller can stop
    rather than accumulate a partial set.
    """
    for attempt in range(retries):
        _throttle()
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA})
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                data = resp.read()
            _consecutive_429[0] = 0
            return data
        except urllib.error.HTTPError as exc:
            if exc.code == 429:
                _consecutive_429[0] += 1
                if _consecutive_429[0] >= MAX_CONSECUTIVE_429:
                    raise Throttled(
                        f"{_consecutive_429[0]} consecutive HTTP 429s from "
                        f"Wikimedia — this IP is rate-limited.\n"
                        f"Wait ~15 minutes and re-run; the manifest is "
                        f"append-only so collection resumes where it stopped.\n"
                        f"Consider --interval 3 or higher."
                    ) from exc
                if attempt < retries - 1:
                    time.sleep(6.0 * (attempt + 1))
                    continue
            if attempt == retries - 1:
                print(f"  ! HTTP {exc.code} {url.rsplit('/', 1)[-1][:44]}",
                      file=sys.stderr)
                return None
        except Exception as exc:                                   # noqa: BLE001
            if attempt == retries - 1:
                print(f"  ! {type(exc).__name__} {url.rsplit('/', 1)[-1][:44]}",
                      file=sys.stderr)
                return None
            time.sleep(1.5 * (attempt + 1))
    return None


def api_get(params: dict) -> dict:
    raw = _fetch(f"{API}?{urllib.parse.urlencode({**params, 'format': 'json'})}",
                 timeout=30)
    if raw is None:
        return {}
    try:
        return json.loads(raw.decode("utf-8"))
    except Exception:                                              # noqa: BLE001
        return {}


def category_files(category: str, want: int) -> List[str]:
    """File titles in a category, paging until ``want`` or exhaustion."""
    titles: List[str] = []
    cont: Optional[str] = None
    while len(titles) < want:
        params = {
            "action": "query", "list": "categorymembers",
            "cmtitle": f"Category:{category}", "cmtype": "file",
            "cmlimit": "500",
        }
        if cont:
            params["cmcontinue"] = cont
        data = api_get(params)
        members = data.get("query", {}).get("categorymembers", [])
        if not members:
            break
        titles += [m["title"] for m in members
                   if m["title"].lower().endswith(IMAGE_EXT)]
        cont = data.get("continue", {}).get("cmcontinue")
        if not cont:
            break
    return titles[:want]


def file_infos(titles: List[str]) -> Iterator[dict]:
    """Thumbnail URL + original dimensions per title, 40 titles per call."""
    for i in range(0, len(titles), 40):
        data = api_get({
            "action": "query", "prop": "imageinfo",
            "iiprop": "url|size|mime",
            "iiurlwidth": str(THUMB_WIDTH),
            "titles": "|".join(titles[i:i + 40]),
        })
        for page in data.get("query", {}).get("pages", {}).values():
            info = (page.get("imageinfo") or [{}])[0]
            # thumburl is the sanctioned bulk endpoint; skip anything without one
            # rather than falling back to the original and collecting 429s.
            if not info.get("thumburl"):
                continue
            yield {
                "title": page.get("title", ""),
                "thumburl": info["thumburl"],
                "orig_width": info.get("width", 0),
                "orig_height": info.get("height", 0),
                "orig_mime": info.get("mime", ""),
            }


def load_seen() -> set:
    if not MANIFEST_PATH.exists():
        return set()
    return {json.loads(l)["sha256"]
            for l in MANIFEST_PATH.read_text(encoding="utf-8").splitlines()
            if l.strip()}


def build(per_class: int, min_pixels: int) -> None:
    from io import BytesIO

    from PIL import Image
    from tqdm import tqdm

    seen = load_seen()
    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    fh = MANIFEST_PATH.open("a", encoding="utf-8")

    print("=" * 74)
    print("  Building internet test set from Wikimedia Commons")
    print(f"  → {OUTPUT_DIR}")
    print(f"  target {per_class}/class · {THUMB_WIDTH}px thumbnails, both classes")
    print("=" * 74)

    try:
        for label, cats in CATEGORIES.items():
            got = 0
            # Even quota per category, but roll unused quota forward: several AI
            # categories hold only a handful of files, and dropping their share
            # would silently halve the fake class.
            for idx, (category, tag) in enumerate(cats):
                remaining_cats = len(cats) - idx
                quota = max(1, (per_class - got + remaining_cats - 1) // remaining_cats)
                titles = category_files(category, quota * 6)
                if not titles:
                    print(f"  [{label}/{tag}] empty category — skipped")
                    continue

                bar = tqdm(total=quota, desc=f"  {label}/{tag:<20}", ncols=74,
                           unit="img", leave=True)
                taken = 0
                for info in file_infos(titles):
                    if taken >= quota:
                        break
                    if info["orig_width"] * info["orig_height"] < min_pixels:
                        continue
                    raw = _fetch(info["thumburl"].split("?", 1)[0])
                    if not raw:
                        continue
                    digest = hashlib.sha256(raw).hexdigest()
                    if digest in seen:
                        continue
                    try:
                        with Image.open(BytesIO(raw)) as im:
                            im.verify()
                        with Image.open(BytesIO(raw)) as im:
                            w, h, fmt = im.size[0], im.size[1], (im.format or "")
                    except Exception:                              # noqa: BLE001
                        continue
                    ext = {"JPEG": "jpg", "PNG": "png",
                           "WEBP": "webp"}.get(fmt.upper())
                    if not ext:
                        continue

                    out_dir = OUTPUT_DIR / label
                    out_dir.mkdir(parents=True, exist_ok=True)
                    name = f"{tag}__{digest[:16]}.{ext}"
                    (out_dir / name).write_bytes(raw)
                    seen.add(digest)
                    fh.write(json.dumps({
                        "sha256": digest,
                        "path": f"{label}/{name}",
                        "label": label,
                        "source": "wikimedia-commons",
                        "category": category,
                        "tag": tag,
                        "title": info["title"],
                        "thumb_url": info["thumburl"].split("?", 1)[0],
                        "width": w, "height": h,
                        "stored_format": fmt.upper(),
                        "orig_width": info["orig_width"],
                        "orig_height": info["orig_height"],
                        "orig_mime": info["orig_mime"],
                        "orientation": ("square" if 0.95 <= w / h <= 1.05
                                        else "landscape" if w > h else "portrait"),
                    }, sort_keys=True) + "\n")
                    fh.flush()
                    taken += 1
                    got += 1
                    bar.update(1)
                bar.close()
                if taken < quota:
                    print(f"    {tag}: {taken}/{quota} (category exhausted)")
            print(f"  [{label}] {got} images")
    except Throttled as exc:
        print(f"\n  STOPPED: {exc}", file=sys.stderr)
    finally:
        fh.close()

    report()


def report() -> None:
    if not MANIFEST_PATH.exists():
        print("No internet test set yet — run without --report first.")
        return
    rows = [json.loads(l) for l in
            MANIFEST_PATH.read_text(encoding="utf-8").splitlines() if l.strip()]
    if not rows:
        print("Manifest is empty.")
        return

    print("\n" + "=" * 74)
    print(f"  INTERNET TEST SET — {len(rows)} images")
    print("=" * 74)
    by = collections.Counter((r["label"], r["tag"]) for r in rows)
    for (label, tag), n in sorted(by.items()):
        print(f"  {label:<6}{tag:<24}{n:>5}")
    print("-" * 74)
    for label in ("real", "fake"):
        print(f"  {label:<6}{'TOTAL':<24}"
              f"{sum(1 for r in rows if r['label'] == label):>5}")

    # The two shortcuts the corpus audit looks for. Both should be *identical*
    # across classes here, because every image went through one thumbnailer.
    print("\n  shortcut audit (both columns should match between classes)")
    fmt = collections.Counter((r["label"], r["stored_format"]) for r in rows)
    for (label, f), n in sorted(fmt.items()):
        print(f"    format      {label:<6}{f:<8}{n:>5}")
    ori = collections.Counter((r["label"], r["orientation"]) for r in rows)
    for (label, o), n in sorted(ori.items()):
        print(f"    orientation {label:<6}{o:<10}{n:>5}")
    for label in ("real", "fake"):
        sub = [r for r in rows if r["label"] == label]
        if sub:
            mp = sum(r["width"] * r["height"] for r in sub) / len(sub) / 1e6
            print(f"    mean pixels {label:<6}{mp:>8.2f} MP")
    print()


def main() -> int:
    global MIN_INTERVAL

    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--per-class", type=int, default=120)
    ap.add_argument("--min-pixels", type=int, default=350_000,
                    help="skip originals smaller than this (drops icons/logos)")
    ap.add_argument("--interval", type=float, default=MIN_INTERVAL,
                    help="seconds between requests; raise if Wikimedia 429s "
                         f"(default {MIN_INTERVAL})")
    ap.add_argument("--report", action="store_true")
    args = ap.parse_args()

    MIN_INTERVAL = max(0.2, args.interval)

    if args.report:
        report()
        return 0
    build(args.per_class, args.min_pixels)
    return 0


if __name__ == "__main__":
    sys.exit(main())
